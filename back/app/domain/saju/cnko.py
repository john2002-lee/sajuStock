def to_ko(table: Mapping[str, str], value: str) -> str:
    """표에서 찾고, 없으면 예외. 매핑되지 않은 중국어를 그대로 통과시키지 않는다."""
    hit = table.get(value)
    if hit is None:
        raise ValueError(f'to_ko: 매핑되지 않은 값 "{value}"')
    return hit


def zhi_pair_to_hangul(pair: str) -> str:
    """지지 두 글자(공망 "辰巳")를 한글로 — "진사"."""
    if len(pair) != 2:
        raise ValueError(f'zhi_pair_to_hangul: 지지 2글자를 기대했으나 "{pair}"')
    return to_ko(ZHI_HANGUL, pair[0]) + to_ko(ZHI_HANGUL, pair[1])
