import type { MetadataRoute } from "next";

/**
 * 크롤러 정책.
 *
 * ## 왜 필요한가 — 색인이 아니라 **상류 호출**이 문제다
 *
 * `/stocks/<문자열>` 은 어떤 입력에도 200 을 준다(못 찾으면 후보 고르기 화면이다).
 * 크롤러에게 그것은 "무한한 유효 페이지"로 보이고, 그 문자열이 KRX 목록에 없으면
 * 백엔드가 그대로 야후 티커로 써서 호출이 나간다. 즉 색인 낭비가 아니라 **우리
 * 상류 쿼터가 크롤러 속도로 소모된다.**
 *
 * 종목일 수 없는 모양에는 `page.tsx` 의 `generateMetadata` 가 `noindex` 를 붙이지만,
 * 그건 이미 요청이 도착한 뒤다. 여기서 미리 막는다.
 *
 * ## 주식 전체가 닫혔다
 *
 * `/stock`(시장 현황)·`/stocks`(랭킹)·`/stocks/screener`(조건 검색)는 allow 에
 * 있었다. 주식이 **개발 전용**으로 내려간 지금 색인시킬 이유가 없다 — 검색 결과로
 * 들어온 사람은 제품의 메인(사주)이 아닌 곳에 떨어지고, 그 화면들은 공개 표면
 * 어디에서도 안내되지 않는다.
 *
 * 차단은 아니다. `robots.txt` 는 요청이고 `/stock` 주소는 그대로 열린다
 * (`app/admin/_components/AdminShell.tsx` 의 입구).
 *
 * ## 무엇을 막나
 *
 *   /stock      시장 현황 — 개발 전용
 *   /stocks     랭킹·조건 검색·종목 상세 — 개발 전용. 종목 상세는 원래 상류 호출
 *               문제로도 막혀 있었다(위 절)
 *   /api/*      BFF. 사람이 볼 화면이 아니고, 자동완성은 팬아웃이 있다
 *   /admin/*    관리자. 익명에게는 404 지만 주소를 광고할 이유가 없다
 *   /watchlist  소유자별 데이터라 색인할 내용이 없다
 *
 * ## 열어 두는 것
 *
 * `/`(사주 입력) · `/saju/intro`(서비스 소개) · `/terms` · `/privacy`.
 * 전부 입력 공간이 유한하고 상류 호출을 늘리지 않는다 — `/` 는 조회가 출생지 목록
 * 하나뿐이고 그것도 캐시된다.
 *
 * `sitemap` 은 두지 않았다. 지금은 색인시킬 안정 URL 집합이 정해지지 않았고
 * (종목 상세는 위 이유로 닫혀 있다), 빈 사이트맵은 없는 것보다 나쁘다.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: "*",
      // `/terms`·`/privacy` 는 **색인되어야 한다** — 마케팅·법적 표면이고
      // 누구의 데이터도 없다. 구매 전에 읽을 수 있어야 하는 문서를 크롤러에게
      // 숨길 이유가 없다.
      //
      // `/saju` 자체는 적지 않는다. 그 주소는 이제 `/` 로 307 이고(`proxy.ts`),
      // 목적지가 이미 열려 있다.
      allow: ["/", "/saju/intro", "/terms", "/privacy"],
      // `/saju/reports/` — **주소 자체가 자격 증명이다.** 크롤러에게 가져가지
      // 말라고 요청하고, 링크를 이미 가진 크롤러는 그 페이지의 `noindex` 가 막는다.
      // `/saju/pay/` 와 `/saju/teaser`·`/saju/report` 는 저장된 결과가 없으면
      // 빈 화면이라 색인할 것이 없다.
      disallow: [
        "/stock",
        "/stocks",
        "/stocks/",
        "/api/",
        "/admin/",
        "/watchlist",
        "/dashboard",
        "/login",
        "/signup",
        "/verify",
        "/saju/reports/",
        "/saju/pay/",
        "/saju/teaser",
        "/saju/report",
        // `/saju/s/` — 공유된 **남의** 여덟 글자다. `shareId` 는 128비트 난수라
        // 추측으로 닿을 수 없지만 크롤러는 링크를 따라온다: 누군가 이 주소를
        // 공개된 곳에 붙이는 순간 검색 결과에 남고, 그때 "링크를 아는 사람만" 이라는
        // 약속이 깨진다. 페이지의 `noindex` 와 이중으로 막는다.
        "/saju/s/",
      ],
    },
  };
}
