/**
 * 이항계수 `C(n, r)`.
 *
 * ## 왜 따로 두나
 *
 * 번호 생성(`generate.ts`)의 가중치가 이 값이다. 오름차순 조합에서 `i` 번째 공이
 * `k` 일 때 남은 `r = 6 - i` 개는 `k+1..45` 중에서 고르므로 경우의 수가
 * `C(45-k, r)` 이고, 그 비율이 곧 조건부 확률이 된다.
 *
 * ## 왜 팩토리얼로 계산하지 않나
 *
 * `45!` 은 `1.2e56` 이다. `Number` 의 안전 정수 한계(`2^53`)를 한참 넘어가므로
 * `n! / (r!(n-r)!)` 로 쓰면 분자·분모가 각각 `Infinity` 가 되고 나눗셈이
 * `NaN` 을 낸다. 가중치 하나가 `NaN` 이면 누적합이 전부 `NaN` 이 되어 번호가
 * 아예 생성되지 않는다.
 *
 * 그래서 `r` 개만 순차로 곱하고 그때그때 나눈다. `result * (n-r+i) / i` 는 매
 * 단계가 이항계수라 **항상 정수로 떨어지고**, 중간값도 작게 유지된다. 이 파일이
 * 다루는 최댓값 `C(44,5) = 1,086,008` 의 중간 곱은 `1.4e8` 수준이다.
 *
 * `r` 을 `min(r, n-r)` 로 접는 것은 대칭성(`C(n,r) = C(n,n-r)`)을 이용해 곱셈
 * 횟수를 줄이는 것이고, 정확도에도 도움이 된다.
 */
export function combi(n: number, r: number): number {
  if (n < 0 || r < 0 || r > n) return 0;

  const k = Math.min(r, n - r);
  let result = 1;
  for (let i = 1; i <= k; i++) {
    result = (result * (n - k + i)) / i;
  }
  // 순차 나눗셈은 정수로 떨어지지만 부동소수 표현상 미세 오차가 남을 수 있다.
  return Math.round(result);
}
