/**
 * 시드를 받는 난수 — 같은 입력이면 같은 번호가 나오게 하는 장치.
 *
 * ## 왜 `Math.random()` 이 아닌가
 *
 * 시드를 받지 못한다. 그러면 **같은 입력에 같은 결과** 를 보장할 수 없고, 그
 * 성질이 없으면 번호 생성을 검증할 방법이 사라진다 — `generate.test.ts` 의
 * 유효성·균등성 검사는 고정된 시드 수만 개를 흘려 넣고 결과를 재현하는 식으로
 * 돈다. 간헐적으로만 실패하는 통계 테스트는 CI 에 둘 수 없다.
 *
 * 화면이 원하는 것은 그 반대처럼 들리는 **방문마다 다른 조합** 이다. 두 요구는
 * 충돌하지 않는다. 난수원을 결정적으로 두고 **시드에 방문 시각을 섞으면**
 * 방문마다 달라지면서도 "무엇을 넣었더니 이것이 나왔다" 를 말할 수 있다. 그래서
 * 문자열을 해시(`cyrb53`)해 시드로 만들고, 그 시드로 `mulberry32` 를 돈다.
 * 시각을 넣는 판단의 근거는 `components/LottoSection.tsx` 에 있다.
 *
 * ## 왜 이 두 개인가
 *
 * 둘 다 짧고(각 10줄 내외) 의존성이 없다. 암호 용도가 아니므로 강도는 필요 없고,
 * 필요한 것은 **재현성과 적당한 균등성** 뿐이다. 번들에 라이브러리를 더할 이유가
 * 없다.
 *
 * `mulberry32` 의 반환값은 `[0, 1)` 이어야 한다 — `generate.ts` 가 `u * total` 로
 * 가중치 누적합을 훑으므로, `u` 가 1 이면 마지막 후보를 넘겨 `undefined` 를
 * 집는다. 그래서 `4294967296` (2^32) 으로 나눈다. 분자는 `>>> 0` 로 32비트
 * 부호없는 정수가 되므로 최대 `2^32 - 1` 이고, 몫은 1 에 닿지 않는다.
 */

/**
 * 문자열 → 53비트 정수 해시.
 *
 * 두 개의 32비트 상태를 굴려 마지막에 합친다. 32비트 하나만 쓰면 `"1241:a:0"` 과
 * `"1241:a:1"` 처럼 한 글자만 다른 입력이 가까운 값으로 몰리는 일이 잦다.
 *
 * 다만 `mulberry32` 가 시드를 `>>> 0` 으로 받으므로 **실제 시드 공간은 2^32** 다
 * (상위 21비트는 버려진다). 조합 수 `C(45,6) = 8.1e6` 에 비하면 500배 이상 넓어
 * 문제가 되지 않지만, 53비트가 끝까지 쓰인다고 오해하지 않도록 적어 둔다.
 */
export function cyrb53(text: string, seed = 0): number {
  let h1 = 0xdeadbeef ^ seed;
  let h2 = 0x41c6ce57 ^ seed;

  for (let i = 0; i < text.length; i++) {
    const ch = text.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }

  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);

  return 2097152 * (h2 >>> 0) + (h1 >>> 11);
}

/** 시드 하나로 `[0, 1)` 난수를 무한히 내는 함수를 만든다. */
export function mulberry32(seed: number): () => number {
  let state = seed >>> 0;

  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
