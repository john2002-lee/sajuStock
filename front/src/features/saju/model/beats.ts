import type { ShamanExpression } from "../components/Shaman";

/**
 * 쓰인 섹션 하나를 웹툰 **비트**의 나열로 바꾼다.
 *
 * 리포트의 한 섹션은 대개 네댓 문단이다. 말풍선 하나로 그리면 그림 옆에 붙은
 * 텍스트 벽이 되는데, 웹툰이 읽히는 방식과 정반대다. 문단으로 쪼개면 페이지가
 * 대화가 된다 — 한 패널에 한 생각, 그에 따라 그녀의 얼굴이 바뀐다.
 *
 * 문단을 하나씩 내보내지 않고 묶는 이유는, 아주 짧은 줄("그러니 조급할 것 없네.")은
 * 자기 프레임에 혼자 있기보다 그것이 닫는 생각과 **함께** 놓여야 하기 때문이다.
 */
export interface Beat {
  text: string;
  expression: ShamanExpression;
}

/**
 * 다음 문단이 새 비트를 시작하기 전까지 비트가 자라는 길이.
 *
 * 감이 아니라 세어서 정했다. 문단당 패널 하나로 두면 리포트 한 편에 말풍선이 35개가
 * 나왔다 — 원문에는 충실하지만 읽기에 지친다. 실제 리포트(8섹션·40문단, 문단 중앙값
 * 71자, 섹션 중앙값 370자)에 대고 재면:
 *
 *     목표 220 → 16개      목표 340 → 10개
 *     목표 300 → 12개      목표 380 →  8개 (섹션당 하나)
 *
 * 300 이면 가장 긴 네 섹션이 둘로 갈려 리듬이 남고 나머지는 한 패널이 된다. 더
 * 올리면 모든 섹션이 말풍선 하나로 붙어 페이지가 대화로 읽히기를 그만둔다.
 *
 * 대가는 분명히 적어 둔다: 가장 긴 말풍선이 110자에서 405자쯤으로 커진다. 말풍선을
 * 줄이면 반드시 하나가 커진다.
 */
const BEAT_TARGET = 300;

/**
 * 문단이 **무엇을 하고 있는지** 말해 주는 단서. 그에 맞춰 그녀의 얼굴이 바뀐다.
 *
 * 실제 생성된 리포트에 대고 다시 만든 목록이다. 첫 판은 `point` 를 강조 어휘(특히,
 * 눈에 띄, 뚜렷)에 걸었는데 40문단 중 72%가 기본값으로 떨어졌고 `joy` 와 `point` 는
 * 한 번도 발동하지 않았다. 모델은 강조하지 않는다 — **진술한다**: "금(金)이 4개",
 * "-5점이 나왔구먼", "28세 갑신 대운". 그래서 `point` 는 이제 사주 어휘 자체에
 * 걸린다. 그것은 구조적이라 부사 목록처럼 흔들리지 않는다.
 *
 * **순서가 곧 설계다.** 거의 모든 문단이 사주를 인용하므로 `point` 는 실제 단서 중
 * **맨 마지막**이다: 평범한 설명의 포괄 항목이며, 경고이기도 하고 위로이기도 한
 * 문단을 삼켜서는 안 된다. 그 위로는 "이건 네가 할 일을 바꾼다" 에서 "이건 그냥
 * 서술이다" 순으로 내려가고, 먼저 맞는 것이 이긴다.
 *
 * **부분 문자열을 조심할 것.** 예전의 `주의` 는 이 제품에서 가장 흔한 낱말인
 * **사주의** 안에서 맞아, 중립적인 요약을 꾸중으로 바꿔 놓았다. 사주/사주의/사주를
 * 안에 들어갈 수 있는 단서는 뒤따르는 조사로 반드시 고정한다.
 *
 * 실제 리포트 기준 분포: point 38%, joy 20%, sad·concern·stern 각 10%, welcome 7%,
 * 기본값 5% — 일곱 포즈가 모두 쓰이고 어느 하나가 지배하지 않는다.
 */
const CUES: Array<{ re: RegExp; expression: ShamanExpression }> = [
  // 경고. 무엇보다 앞선다: 읽는 사람이 놓치면 안 된다.
  // `주의` 는 조사로 고정해 `사주의` 안에서 발동하지 않게 한다.
  {
    re: /조심|유의|주의(하|해|를|가)|경계|삼가|무리(하|는|하지)|과욕|성급|조급|욕심|채찍질|과로|기복을 줄|달달 볶/,
    expression: "stern",
  },
  // 힘든 대목. 긍정보다 위에 두어 "힘든 시기를 지나 좋아진다" 가 어려움을 인정한
  // 채로 전달되게 한다.
  { re: /어려|힘들|아쉽|안타깝|고비|막히|버거|외로|고뇌|스트레스|텅 빈|옅어|녹아내리|피곤/, expression: "sad" },
  // 읽는 사람에게 건네는 조언. 프롬프트가 고정한 명령형이다.
  { re: /하시게|해 보시게|하시길|권하|좋겠네|좋네|필요하네|연습|살아가시게|들어보시게|안아주/, expression: "welcome" },
  // 단서를 달거나 균형을 잡는 틀. `쉽구먼`·`쉬우니` 는 일부러 넣지 않았다:
  // 이 말투에서 "~하기 쉽다" 는 "~하는 편이다" 라 칭찬("신뢰를 얻기 쉽구먼")을
  // 단서로 잘못 잡았다.
  { re: /다만|하지만|그러나|반면|비록|경우에 따라|사람에 따라|기보다는|않도록/, expression: "concern" },
  // 위로와 좋은 결과.
  { re: /도타운|굳건|버틸 힘|제자리를 찾|의연|신뢰를 얻|탁월|돋보이|결실|잘 맞|인연이 깊|균형을 이루/, expression: "joy" },
  // 사주를 짚는 중. 어휘가 아니라 구조다: 간지 한자, 십신 이름, 개수, 점수,
  // 대운 나이 — 어느 것이든 그녀가 계산된 값을 읽고 있다는 뜻이다.
  {
    re: /[甲乙丙丁戊己庚辛壬癸子丑寅卯辰巳午未申酉戌亥金木水火土]|비견|겁재|식신|상관|편재|정재|편관|정관|편인|정인|관성|재성|인성|식상|공망|\d+\s*개|\d+\s*점|\d+세 .{0,3}대운|중화|실령|득령|득지|득세/,
    expression: "point",
  },
];

/** 부분 문자열 회귀 테스트용으로 노출한다. 렌더 경로의 일부는 아니다. */
export function cueFor(text: string): ShamanExpression | null {
  for (const { re, expression } of CUES) {
    if (re.test(text)) return expression;
  }
  return null;
}

function expressionFor(text: string, index: number): ShamanExpression {
  // 단서가 없으면: 섹션은 독자를 마주 보며 열고, 그 뒤로는 평범한 말로 가라앉는다.
  return cueFor(text) ?? (index === 0 ? "welcome" : "speak");
}

/**
 * `body` 를 비트로 나눈다. 문단이 자연스러운 단위이고(모델이 빈 줄로 나눠 쓴다),
 * 연속된 문단을 `BEAT_TARGET` 까지 합쳐 한 섹션이 다섯이 아니라 한둘의 패널이 되게 한다.
 */
export function toBeats(body: string): Beat[] {
  const paragraphs = body
    .split(/\n{2,}/)
    .map((p) => p.trim())
    .filter(Boolean);

  if (paragraphs.length === 0) return [];

  // 목표 길이에 닿을 때까지 현재 비트에 계속 더하고, 넘으면 새로 시작한다.
  // 예전 규칙은 둘 중 하나가 **짧을 때만**(60자 미만) 합쳤는데 모델의 문단은
  // 48~111자라 거의 발동하지 않았고, 결국 문단마다 패널이 하나씩 생겼다.
  const grouped: string[] = [];
  for (const p of paragraphs) {
    const last = grouped[grouped.length - 1];
    if (last !== undefined && last.length < BEAT_TARGET) {
      grouped[grouped.length - 1] = `${last}\n\n${p}`;
    } else {
      grouped.push(p);
    }
  }

  return grouped.map((text, i) => ({ text, expression: expressionFor(text, i) }));
}
