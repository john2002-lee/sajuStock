/**
 * 추석·오픈 기념 무료 기간.
 *
 * ## 무엇을 하나
 *
 * 이 기간에는 정밀 리포트를 결제 없이 준다. **결제 코드는 그대로 둔다** — 지우면
 * 기간이 끝났을 때 되살려야 하고, 되살리는 쪽이 훨씬 위험하다. 결제창을 여는
 * 자리에서 이 함수 하나로 갈라지고, 기간이 지나면 저절로 원래 흐름으로 돌아온다
 * (`components/PayButton.tsx`).
 *
 * ## 왜 UTC 밀리초 하나로 박아 두나
 *
 * 화면에 적는 "9월 30일" 은 한국 날짜인데 서버(Vercel 함수)는 UTC 로 돈다.
 * `getMonth()`·`getDate()` 같은 지역 시간대 메서드로 비교하면 개발 기계(KST)에서는
 * 맞고 배포에서는 아홉 시간 어긋난다 — **마지막 날이 통째로 사라진다.**
 *
 * 그래서 경계를 절대시각 두 개로 둔다. KST 2026-09-18 00:00:00.000 =
 * UTC 2026-09-17 15:00:00.000, KST 2026-09-30 23:59:59.999 =
 * UTC 2026-09-30 14:59:59.999. 한국은 1988년 이후 서머타임이 없어 오프셋이 고정이다.
 *
 * 시작 경계도 둔다. 처음에는 종료일만 보게 했는데 — 일찍 온 사람에게 무료로 주는
 * 것은 아무것도 망가뜨리지 않는다는 이유였다 — 그러면 화면에 적은 기간과 실제
 * 동작이 어긋난다. **표기한 기간이 곧 코드의 기간이어야** 화면이 거짓을 말하지 않는다.
 */

/** KST 2026-09-18 00:00:00.000 — 이 순간부터 무료다. */
const FREE_FROM_MS = Date.UTC(2026, 8, 17, 15, 0, 0, 0);

/** KST 2026-09-30 23:59:59.999 — 이 순간까지 무료다. */
const FREE_UNTIL_MS = Date.UTC(2026, 8, 30, 14, 59, 59, 999);

/** 화면에 적는 행사 기간. 두 날짜 모두 위 경계와 같은 날을 가리킨다(테스트가 지킨다). */
export const FREE_EVENT_PERIOD = "2026.9.18~9.30";

/**
 * **`now` 는 반드시 서버 시각이어야 한다.**
 *
 * 브라우저에서 `new Date()` 로 부르면 사용자가 기기 시계를 옮기는 것만으로 무료
 * 경로가 열린다. 그래서 화면들은 이 함수를 직접 부르지 않고, 서버 컴포넌트가
 * 판정한 값을 prop 으로 받는다 — 팝업 · 티저 · 결제 버튼이 모두 한 번의 서버
 * 판정을 나눠 쓴다.
 *
 * (이 함수가 막는 것은 **결제 UI 를 여는 것** 까지다. 리포트 생성 경로 자체는
 * 결제 이전부터 게이트가 없었고, 그 설계는 이 이벤트가 만든 것이 아니다.)
 */
export function isFreeEvent(now: Date): boolean {
  const at = now.getTime();
  return at >= FREE_FROM_MS && at <= FREE_UNTIL_MS;
}
