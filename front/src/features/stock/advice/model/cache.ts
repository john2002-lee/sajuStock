// AI 판단 캐시 정책 — 클라이언트 쪽 몫.
//
// 백엔드에도 같은 이름의 캐시가 있다(`back/app/services/advice_cache.py`). 둘은
// 경쟁하지 않고 **층을 이룬다**. 나누는 기준은 "무엇을 아끼는가" 다.
//
//   ┌─ 클라이언트 캐시 (여기) ──────────────────────────────────────┐
//   │ 아끼는 것: 네트워크 왕복 · 진행 바를 다시 보는 시간            │
//   │ 판단 근거: staleTime — 화면을 닫았다 다시 열어도 요청 0회      │
//   └───────────────────────────────────────────────────────────────┘
//                              ↓ staleTime 이 지난 뒤에만 요청이 나간다
//   ┌─ 서버 캐시 (advice_cache.py) ────────────────────────────────┐
//   │ 아끼는 것: LLM 4회 (진짜 비용)                                │
//   │ 판단 근거: 뉴스 지문 — 기사가 그대로면 재분석하지 않는다       │
//   └───────────────────────────────────────────────────────────────┘
//
// 그래서 **클라이언트가 "새 기사가 떴는지" 를 판단하지 않는다.** 그건 뉴스 목록을
// 손에 쥔 서버만 알 수 있다. 클라이언트는 staleTime 이 지나면 그냥 다시 물어보고,
// 새 기사가 없으면 서버가 LLM 없이 즉시 같은 답을 돌려준다.

import type { AgentOpinion, Decision } from "./types";

/** React Query 캐시에 들어가는 것 — 스트림이 끝나고 남는 결과물 */
export interface AdviceResult {
  agents: AgentOpinion[];
  decision: Decision;
}

/**
 * 캐시 키. `fallback` 을 포함하는 이유는 그 모드가 **일부러 실패를 재현하는**
 * 개발용 경로라, 정상 결과와 같은 칸에 담기면 서로를 덮어쓰기 때문이다.
 */
export function adviceQueryKey(symbol: string, fallback = false) {
  return ["advice", symbol, fallback] as const;
}

/**
 * 이 시간 안에는 같은 종목을 다시 열어도 요청이 나가지 않는다.
 *
 * 서버 TTL(기본 600초)과 같은 값으로 맞춘다. 클라이언트가 더 짧으면 서버 캐시에만
 * 닿는 헛 요청이 늘고, 더 길면 새 기사가 떴는데도 화면이 그걸 모르는 구간이 생긴다.
 * 한쪽을 바꾸면 다른 쪽도 바꿔야 한다 — `advice_cache_ttl_seconds`.
 */
export const ADVICE_STALE_MS = 10 * 60_000;

/**
 * 화면에서 사라진 뒤 캐시를 들고 있는 시간. staleTime 보다 넉넉해야 뒤로가기·
 * 드로어 재개봉이 즉시 그려진다.
 */
export const ADVICE_GC_MS = 30 * 60_000;

/**
 * 백엔드 예산 기본값(`advice_budget_seconds`)에 대한 **설계 시점의 가정**이다.
 *
 * 화면 문구는 이 값을 쓰지 않는다. 실제 예산은 서버가 진행 이벤트에 실어 보내고
 * (`AdviceStreamEvent.budgetMs`) 진행 표시가 그것을 읽는다 — 손으로 복사해 둔
 * 숫자는 백엔드 설정이 바뀌는 순간 거짓말이 되기 때문이다.
 *
 * 그래도 여기 남은 이유는 하나다: `AI_TIMEOUT_MS` 가 예산보다 넉넉한지를
 * **테스트로** 고정하는 기준값. 그 부등식이 깨지면 규칙 기반 착지가 사용자에게
 * 도착하기 직전에 잘린다.
 */
export const ADVICE_BUDGET_MS = 90 * 1000;

/**
 * **서버가 알려 준** 예산의 이 비율을 넘기면 진행 표시가 마무리를 예고한다.
 *
 * 예고가 있으면 착지가 사고가 아니라 설계로 읽힌다. 없으면 예산이 끝나는 순간의
 * '규칙 기반 판단' 이 사용자에게는 그냥 고장으로 보인다.
 */
export const ADVICE_WARN_RATIO = 0.7;

/**
 * '전체 AI 분석' 한 번에 돌릴 수 있는 종목 수 상한.
 *
 * **이 숫자가 곧 비용 상한이다** — 종목당 LLM 4회이므로 10종목이면 40회다.
 * 상한이 없던 시절 관심종목 20개를 담아 둔 사용자는 버튼 한 번에 80회를 태웠고,
 * 그게 의도였는지 오조작이었는지 구분할 방법이 없었다.
 *
 * 초과분은 조용히 자르지 않고 호출부가 몇 개를 뺐는지 돌려받아 화면에 밝힌다 —
 * 20개를 골랐는데 10개만 도는 것을 말없이 하면 버그로 읽힌다.
 */
export const MAX_BULK_SYMBOLS = 10;
