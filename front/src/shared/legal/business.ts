/**
 * 사업자 정보 — 전자상거래법이 **구매 전에** 노출하도록 요구하는 항목들.
 *
 * ## 왜 한곳에 모으나
 *
 * 이 값들은 약관과 개인정보처리방침 두 페이지에 각각 필요하다. 양쪽에 적어 두면
 * 실제 정보로 바꿀 때 한쪽만 고쳐지고, 그 순간 **두 법적 문서가 서로 다른 사업자를
 * 가리킨다.** 고칠 곳이 하나여야 그 사고가 나지 않는다.
 *
 * ## 지금 값은 전부 임시다 — 그리고 그 사실이 화면에 보인다
 *
 * 위험한 것은 값이 비어 있는 것이 아니라 **그럴듯하게 채워져 있는 것**이다. 비어
 * 있으면 미완성임을 스스로 외치지만, 그럴듯한 값은 완성된 것처럼 보인다. 그래서
 * 셋을 함께 둔다:
 *
 *  1. 값 자체를 오인할 수 없게 만든다 — `000-00-00000` 은 유효한 사업자등록번호가
 *     아니고, 나머지 항목도 "(임시)" 를 달고 있다.
 *  2. 페이지가 `IS_PLACEHOLDER` 동안 `PLACEHOLDER_NOTICE` 를 함께 렌더한다.
 *  3. 테스트가 그 대응을 강제한다 — 플래그만 내리고 값을 안 바꾸는 것도, 값만 바꾸고
 *     고지를 안 지우는 것도 걸린다.
 *
 * 실제 정보를 받으면: 아래 값을 채우고 `IS_PLACEHOLDER` 를 false 로 내린다.
 *
 * 이 파일이 `features/saju` 가 아니라 `shared/` 에 있는 이유: 법적 문서는 서비스가
 * 아니라 **제품 전체**에 붙는다. 사주 결제가 그것을 필요하게 만들었지만, 계정과
 * 관심종목을 다루는 주식 쪽도 같은 문서가 덮는다.
 */

/** 아래 값이 실제 사업자 정보가 아니라 임시값임을 나타낸다. */
export const IS_PLACEHOLDER = true;

export interface BusinessInfo {
  상호: string;
  대표자: string;
  사업자등록번호: string;
  통신판매업신고번호: string;
  주소: string;
}

/**
 * 값은 서로 달라야 한다. 빈 항목을 모두 같은 문구로 채우면 표에서 어느 줄이
 * 무엇인지 구분되지 않고, 테스트도 어느 항목을 집었는지 알 수 없다.
 */
export const BUSINESS_INFO: BusinessInfo = {
  상호: "(임시) 상호",
  대표자: "(임시) 대표자명",
  사업자등록번호: "000-00-00000",
  통신판매업신고번호: "(임시) 통신판매업신고번호",
  주소: "(임시) 사업장 주소",
};

/** 개인정보 보호책임자 — 개인정보 보호법이 별도로 요구하는 항목. */
export const PRIVACY_OFFICER = {
  성명: "(임시) 책임자 성명",
  직위: "(임시) 직위",
  연락처: "(임시) 연락처",
};

/**
 * 임시값이 노출되는 동안 함께 보여야 하는 문구.
 *
 * 이것이 있어야 표를 읽은 사람이 "아직 등록되지 않은 사업자" 와 "잘못 적힌 사업자"
 * 를 구분할 수 있다.
 */
export const PLACEHOLDER_NOTICE =
  "아래 사업자 정보는 아직 등록되지 않은 임시값입니다. 실제 서비스 개시 전에 " +
  "실제 정보로 교체됩니다.";

/** 표로 그리기 위한 `[라벨, 값]` 목록. 순서가 곧 표시 순서다. */
export function businessRows(): Array<[string, string]> {
  return Object.entries(BUSINESS_INFO) as Array<[string, string]>;
}
