/**
 * 파는 물건이 무엇인지 **한 곳에서** 말한다.
 *
 * ## 왜 모으나
 *
 * 같은 상품을 지금 네 군데가 각자 설명하고 있었다 — 소개 페이지의 무료/유료 목록,
 * 티저 구매 카드의 한 줄 설명, 결제 버튼이 토스에 보내는 `orderName`, 그리고
 * 약관. 그중 `orderName`("AI Of Tellers 정밀 사주 리포트")은 **화면 어디에도 없이**
 * 결제 내역과 카드 명세서에만 찍혔다. 산 사람이 자기가 무엇을 샀는지 확인하려면
 * 사이트에 없는 이름을 봐야 했다.
 *
 * 전자상거래법이 구매 전에 요구하는 것도 정확히 이것이다 — 상품명, 구성, 가격,
 * 제공 시점. 네 벌로 적어 두면 그중 하나는 반드시 낡는다.
 *
 * ## 왜 `features/saju` 가 아니라 `shared/legal` 인가
 *
 * 처음에는 사주 feature 안에 두었다. 그런데 **이용약관이 이 값을 필요로 한다** —
 * 전자상거래법이 요구하는 거래조건(상품명·구성·제공 시점)이 곧 이 내용이기
 * 때문이다. 약관이 `features/saju` 를 깊게 import 하면 두 규칙이 깨진다:
 * 경계는 배럴로만 노출한다는 것(CONVENTIONS 4장 5번), 그리고 사주를 접을 때
 * `features/saju/` 를 폴더째 지우면 끝이어야 한다는 것 — 약관이 딸려 죽는다.
 *
 * 그래서 `shared/` 로 올렸다. 위 규칙이 그렇게 하라고 적혀 있다(3번: 필요하면
 * `app/` 에서 조립하거나 `shared/` 로 승격한다). 옆의 `business.ts`·`refund.ts`
 * 와 같은 자리다 — 셋 다 **파는 사람이 사기 전에 밝혀야 하는 것**이다.
 *
 * ## 가격은 여기 없다
 *
 * 가격만은 **서버가 정한다**(`GET /saju/payment/config`). 화면·결제 요청·승인 검증
 * 셋이 같은 값을 봐야 하고, 복사본이 생기면 그 셋이 어긋나는 순간이 온다
 * (`model/types.ts` 의 `PaymentConfig`). 공개 소개 페이지에서 쓰는 표시용 가격만
 * 예외이며 그쪽은 `lib/config/public.ts` 에 있다.
 */

