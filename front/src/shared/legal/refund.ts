/**
 * 환불에 관해 **여러 화면이 똑같이 말해야 하는 문장들.**
 *
 * ## 왜 상수로 두나
 *
 * "영업일 기준 1일 이내로 전액 환불" 은 약관 제6조와 환불정책 페이지가 함께
 * 말하는 약속이고, **백엔드도 같은 문장을 들고 있다**
 * (`back/app/services/saju_order_service.py` 의 `needs_attention` 메시지 —
 * 결제가 미상일 때 화면에 그대로 내려간다).
 *
 * 세 곳이 각자 적어 두면 한 곳만 고쳐지는 날이 오고, 그날 **화면이 약관보다 짧은
 * 기한을 약속**하거나 그 반대가 된다. 프런트 두 곳은 여기서 가져다 쓰고, 백엔드
 * 문장을 고칠 때는 여기도 함께 고친다(그쪽 주석이 같은 경고를 담고 있다).
 *
 * ## 이 약속은 법정 기한보다 짧다
 *
 * 전자상거래법이 요구하는 것은 3영업일이다. 1영업일로 좁혀 둔 것은 의도된
 * 선택이며, **사람이 토스 대시보드에서 직접 처리한다**(환불 API 가 없다 —
 * `back/app/integrations/payment/`). 지킬 수 없게 되면 법정 기한으로 늘리는 쪽이
 * 맞다. 지키지 못할 약속을 적어 두는 것이 안 적는 것보다 나쁘다.
 */

